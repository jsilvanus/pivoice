#!/usr/bin/env node
// Generates src/generated/commands.js from openapi/openapi.yaml. The CLI reads
// that table, so every operation in the spec is a command, and nothing is
// hand-written per endpoint. Run with --check in CI to catch drift.
import { readFile, writeFile } from 'node:fs/promises';
import { realpathSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { parse } from 'yaml';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SPEC_FILE = path.join(ROOT, 'openapi', 'openapi.yaml');
export const OUTPUT_FILE = path.join(ROOT, 'src', 'generated', 'commands.js');
const METHODS = ['get', 'put', 'post', 'delete'];

export const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

export function buildCommands(doc) {
  const commands = [];
  for (const [route, item] of Object.entries(doc.paths ?? {})) {
    for (const method of METHODS) {
      const op = item[method];
      if (!op) continue;
      if (!op.operationId) throw new Error(`${method.toUpperCase()} ${route} has no operationId`);
      const content = op.responses?.['200']?.content ?? {};
      commands.push({
        operationId: op.operationId,
        command: kebab(op.operationId),
        method: method.toUpperCase(),
        path: route,
        summary: op.summary ?? '',
        pathParams: [...route.matchAll(/\{(\w+)\}/g)].map((m) => m[1]),
        hasBody: Boolean(op.requestBody),
        streams: 'text/event-stream' in content,
        auth: op.security?.length === 0 ? 'none' : 'bearer',
      });
    }
  }
  const names = commands.map((c) => c.operationId);
  const dup = names.find((n, i) => names.indexOf(n) !== i);
  if (dup) throw new Error(`duplicate operationId ${dup}`);
  return commands.sort((a, b) => a.command.localeCompare(b.command));
}

export function renderModule(commands) {
  return `// Generated by scripts/generate-cli.js from openapi/openapi.yaml. Do not edit.\nexport const commands = ${JSON.stringify(commands, null, 2)};\n`;
}

export async function generate({ check = false } = {}) {
  const spec = parse(await readFile(SPEC_FILE, 'utf8'));
  const next = renderModule(buildCommands(spec));
  if (check) {
    const current = await readFile(OUTPUT_FILE, 'utf8').catch(() => '');
    if (current !== next) throw new Error('src/generated/commands.js is out of date; run npm run generate');
    return false;
  }
  await writeFile(OUTPUT_FILE, next);
  return true;
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const check = process.argv.includes('--check');
    await generate({ check });
    console.log(check ? 'generated CLI table is up to date' : `wrote ${path.relative(ROOT, OUTPUT_FILE)}`);
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
}
